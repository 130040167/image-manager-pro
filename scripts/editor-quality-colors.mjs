import assert from 'node:assert/strict'
import path from 'node:path'

export async function checkCustomColors(page, output, id) {
  const color = () => page.evaluate(id => window.__IM_EDITOR_INSTANCE__.state.getObject(id).measurementLabel.color, id)
  const open = () => page.getByRole('button', { name: '标注颜色选择', exact: true }).click()
  await open()
  await page.getByRole('button', { name: '色板 #ffffff', exact: true }).click()
  const palette = page.locator('.fp-color-popover > .fp-color-palette')
  const dimensions = await palette.evaluate(el => [...el.querySelectorAll(':scope > button')].map((button) => {
    const rect = button.getBoundingClientRect()
    return [rect.width, rect.height, rect.y]
  }))
  assert.equal(dimensions.length, 8)
  assert(dimensions.every(([width, height, y]) => width === 20 && height === 20 && y === dimensions[0][2]), JSON.stringify(dimensions))
  assert((await page.locator('.fp-color-popover .fp-color-custom-rainbow').evaluate(el => getComputedStyle(el).backgroundImage)).includes('conic-gradient'))
  await palette.locator('.fp-color-custom').click()
  const panel = page.locator('.fp-custom-color-panel')
  const hex = page.getByRole('textbox', { name: 'HEX', exact: true })
  await hex.fill('#123456')
  assert.equal(await color(), '#123456')
  await hex.press('Escape')
  assert.equal(await page.locator('.fp-color-popover').count(), 1)
  await palette.locator('.fp-color-custom').click()
  assert.equal(await panel.getByRole('button', { name: '最近使用 #123456', exact: true }).count(), 1)
  assert.equal(await page.getByRole('spinbutton', { name: 'R', exact: true }).inputValue(), '18')
  assert.equal(await page.getByRole('spinbutton', { name: 'G', exact: true }).inputValue(), '52')
  assert.equal(await page.getByRole('spinbutton', { name: 'B', exact: true }).inputValue(), '86')
  for (const [channel, value] of [['R', '10'], ['G', '20'], ['B', '30']])
    await page.getByRole('spinbutton', { name: channel, exact: true }).fill(value)
  await page.getByRole('spinbutton', { name: 'B', exact: true }).press('Tab')
  assert.equal(await color(), '#0a141e')
  assert.equal(await hex.inputValue(), '#0a141e')
  assert.equal(await page.locator('.fp-color-popover').count(), 1, 'Nested picker dismissed its parent')
  assert.equal(await panel.getByRole('button', { name: /^推荐色 / }).count(), 8)
  await panel.getByRole('button', { name: '推荐色 #0ea5e9', exact: true }).click()
  assert.equal(await color(), '#0ea5e9')
  await panel.getByRole('button', { name: '最近使用 #0a141e', exact: true }).click()
  assert.equal(await color(), '#0a141e')
  const rect = await panel.boundingBox()
  const viewport = page.viewportSize()
  assert(rect.x >= 0 && rect.y >= 0 && rect.x + rect.width <= viewport.width && rect.y + rect.height <= viewport.height, JSON.stringify(rect))
  await page.screenshot({ path: path.join(output, 'editor-custom-colors-dark.png') })
  await hex.press('Escape')
  assert.equal(await panel.count(), 0)
  assert.equal(await page.locator('.fp-color-popover').count(), 1)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.fp-color-popover').count(), 0)
  await page.getByRole('button', { name: '切换主题', exact: true }).click()
  await open()
  await palette.locator('.fp-color-custom').click()
  assert.equal(await panel.getByRole('button', { name: '最近使用 #0a141e', exact: true }).count(), 1)
  await page.screenshot({ path: path.join(output, 'editor-custom-colors-light.png') })
  await hex.press('Escape')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '切换主题', exact: true }).click()
  // Persisted recent colors are shared by creation panels, not just the edited object's field.
  await page.locator('.fp-toolbar button[title="测量"]').click()
  await page.locator('.fp-measure-options .fp-color-custom').click()
  assert.equal(await page.getByRole('button', { name: '最近使用 #0a141e', exact: true }).count(), 1)
  await page.getByRole('textbox', { name: 'HEX', exact: true }).press('Escape')
  await page.evaluate(() => {
    document.dispatchEvent(new CustomEvent('image-editor-end-measure'))
    window.__IM_EDITOR_INSTANCE__.endAll()
  })
}

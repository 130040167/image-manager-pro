import { createHash } from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'third-party-licenses')
const marker = '.generated-by-build-third-party-notices'
const excludedRoots = new Set(['ua-parser-js'])
const legalName = /^(?:licen[cs]es?|notices?|copying|copyright)(?:$|[._-])/i
const legalDirectory = /^(?:licen[cs]es?|notices?|legal)$/i
const textExtension = /\.(?:txt|md|markdown|rst|html?)$/i
const seen = new Set()
const packages = []
const missing = new Set()

async function exists(file) {
  try {
    await fs.access(file)
    return true
  }
  catch {
    return false
  }
}

async function resolvePackage(name, from) {
  let current = from
  for (;;) {
    const candidate = path.join(current, 'node_modules', name, 'package.json')
    if (await exists(candidate))
      return fs.realpath(path.dirname(candidate))
    const parent = path.dirname(current)
    if (parent === current)
      return undefined
    current = parent
  }
}

async function findLegalFiles(directory, relative = '', withinLegalDirectory = false) {
  const result = []
  const entries = await fs.readdir(path.join(directory, relative), { withFileTypes: true })
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.isSymbolicLink() || entry.name === 'node_modules' || entry.name === '.git')
      continue
    const child = path.join(relative, entry.name)
    if (entry.isDirectory()) {
      result.push(...await findLegalFiles(
        directory,
        child,
        withinLegalDirectory || legalDirectory.test(entry.name),
      ))
    }
    else if (entry.isFile() && (legalName.test(entry.name)
      || (withinLegalDirectory && (!path.extname(entry.name) || textExtension.test(entry.name))))) {
      result.push(child)
    }
  }
  return result
}

async function visit(name, from, optional = false) {
  const directory = await resolvePackage(name, from)
  if (!directory) {
    if (!optional)
      missing.add(`${name} (required by ${path.relative(root, from) || 'root'})`)
    return
  }
  if (seen.has(directory))
    return
  seen.add(directory)
  const manifest = JSON.parse(await fs.readFile(path.join(directory, 'package.json'), 'utf8'))
  const files = await findLegalFiles(directory)
  const relative = path.relative(root, directory).split(path.sep).join('/')
  const suffix = createHash('sha256').update(relative).digest('hex').slice(0, 10)
  const folder = `${manifest.name.replace(/[^a-z0-9._-]/gi, '_')}--${manifest.version}--${suffix}`
  const repository = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url
  packages.push({
    name: manifest.name,
    version: manifest.version,
    license: manifest.license || manifest.licenses || 'UNKNOWN',
    source: repository || manifest.homepage || `https://www.npmjs.com/package/${manifest.name}/v/${manifest.version}`,
    installedPath: relative,
    files: files.map(file => file.split(path.sep).join('/')),
    directory,
    folder,
  })
  const optionalDependencies = manifest.optionalDependencies || {}
  const dependencies = { ...manifest.dependencies, ...optionalDependencies }
  for (const [dependency] of Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)))
    await visit(dependency, directory, dependency in optionalDependencies)
  // Installed peers may also contribute code; absent peers are not copied.
  for (const peer of Object.keys(manifest.peerDependencies || {}).sort())
    await visit(peer, directory, true)
}

const manifest = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'))
const roots = { ...manifest.devDependencies, ...manifest.dependencies, ...manifest.optionalDependencies }
for (const name of Object.keys(roots).sort()) {
  if (!excludedRoots.has(name))
    await visit(name, root, name in (manifest.optionalDependencies || {}))
}
if (missing.size)
  throw new Error(`Install the complete dependency graph before generating notices:\n${[...missing].join('\n')}`)

packages.sort((a, b) => a.name.localeCompare(b.name)
  || a.version.localeCompare(b.version) || a.installedPath.localeCompare(b.installedPath))

// Only replace this script's own output, at the fixed directory under this repository.
if (path.dirname(output) !== root || path.basename(output) !== 'third-party-licenses')
  throw new Error('Unexpected notice output directory')
if (await exists(output)) {
  if (!(await exists(path.join(output, marker))))
    throw new Error(`Refusing to replace an unmanaged directory: ${output}`)
  await fs.rm(output, { recursive: true })
}
await fs.mkdir(output, { recursive: true })
await fs.writeFile(path.join(output, marker), 'Generated by scripts/build-third-party-notices.mjs\n')

for (const pkg of packages) {
  for (const relative of pkg.files) {
    const target = path.join(output, pkg.folder, relative)
    await fs.mkdir(path.dirname(target), { recursive: true })
    await fs.copyFile(path.join(pkg.directory, relative), target)
  }
}

const inventory = packages.map(({ directory, ...pkg }) => pkg)
await fs.writeFile(path.join(output, 'index.json'), `${JSON.stringify(inventory, null, 2)}\n`)
function escapeCell(value) {
  return String(typeof value === 'string' ? value : JSON.stringify(value))
    .replaceAll('|', '\\|').replaceAll('\n', ' ')
}
const rows = packages.map(pkg => [
  escapeCell(pkg.name),
  escapeCell(pkg.version),
  escapeCell(pkg.license),
  escapeCell(pkg.source),
  pkg.files.length
    ? pkg.files.map(file => `[${escapeCell(file)}](${encodeURI(`${pkg.folder}/${file}`).replaceAll('(', '%28').replaceAll(')', '%29')})`).join('<br>')
    : 'No separate license/notice file supplied by the installed package',
].join(' | '))
await fs.writeFile(path.join(output, 'README.md'), [
  '# Dependency License Inventory',
  '',
  'Generated from installed dependencies, optional dependencies, build dependencies, and their installed dependency/peer graphs. This is a conservative superset, not a list of components shipped in the extension. License metadata is reproduced from package manifests; complete supplied legal texts are copied without modification. Refer to index.json for installed package paths.',
  '',
  '| Package | Version | Declared License | Source | Supplied Legal Texts |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map(row => `| ${row} |`),
  '',
].join('\n'))
console.log(`Collected ${packages.length} installed packages and ${packages.reduce((sum, pkg) => sum + pkg.files.length, 0)} legal files in ${output}`)
